/// 进度条左端和右端的形状。
enum BarCapShape {
  /// 左端和右端是圆形的。
  round,

  /// 左端和右端是方形的。
  square,
}

/// 时间标签相对于进度条的位置。
enum TimeLabelLocation {
  /// 时间标签显示在进度条上方。
  ///
  /// | 01:23              05:00 |
  /// | -------O---------------- |
  above,

  /// 时间标签显示在进度条下方。
  ///
  /// | -------O---------------- |
  /// | 01:23              05:00 |
  below,

  /// 时间标签显示在进度条两侧。
  ///
  /// | 01:23 -------O---------------- 05:00 |
  sides,

  /// 不显示时间标签。
  ///
  /// | -------O---------------- |
  none,
}

/// 右侧时间标签的显示类型。
enum TimeLabelType {
  /// 右侧标签显示总时长。
  ///
  /// | -------O---------------- |
  /// | 01:23              05:00 |
  totalTime,

  /// 右侧标签显示剩余时间（负数形式）。
  ///
  /// | -------O---------------- |
  /// | 01:23             -03:37 |
  remainingTime,
}

/// 可拖拽滑块的视觉形状。
enum ThumbShape {
  /// 实心圆形，半径为 [thumbRadius]。
  circle,

  /// 实心正方形，边长为 2 * [thumbRadius]。
  square,

  /// 实心菱形（正方形旋转 45 度）。
  diamond,

  /// 向上的三角形。
  triangle,

  /// 使用调用者提供的自定义绘制器。
  custom,
}
